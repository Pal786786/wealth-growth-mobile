"""AI Market Summary Engine — Sprint 7C.2

Daily / Weekly / Intraday market summaries generated by Claude Sonnet 4.5.
Each summary aggregates top gainers/losers from the cache and asks the LLM
for a concise narrative. Falls back to a deterministic template if the LLM
is unavailable.

Collection: `ai_market_summaries`
"""
from __future__ import annotations
import logging
import os
import uuid
from datetime import datetime, timezone, timedelta
from typing import Any, Dict, List, Optional

from dotenv import load_dotenv

try:
    from emergentintegrations.llm.chat import LlmChat, UserMessage  # type: ignore
    HAS_LLM = True
except Exception:
    LlmChat = UserMessage = None  # type: ignore
    HAS_LLM = False

load_dotenv()
logger = logging.getLogger("ai_news.summary")

EMERGENT_KEY = (os.environ.get("EMERGENT_LLM_KEY") or "").strip()
MODEL_PROVIDER = "anthropic"
MODEL_NAME = "claude-sonnet-4-5-20250929"

COLL = "ai_market_summaries"
VALID_TYPES = {"intraday", "daily", "weekly"}


def _now() -> datetime:
    return datetime.now(timezone.utc)


async def _read_movers(db, limit: int = 20) -> List[Dict[str, Any]]:
    cur = db.market_price_cache.find({}, {"_id": 0}).limit(50)
    rows = [d async for d in cur]
    # Filter to those with a change_pct value
    rows = [r for r in rows if r.get("change_pct") is not None]
    rows.sort(key=lambda r: abs(r.get("change_pct") or 0), reverse=True)
    return rows[:limit]


def _period_bounds(summary_type: str, now: datetime):
    if summary_type == "intraday":
        return now - timedelta(hours=6), now
    if summary_type == "daily":
        return now - timedelta(days=1), now
    return now - timedelta(days=7), now


def _fallback_narrative(summary_type: str, movers: List[Dict[str, Any]]) -> Dict[str, Any]:
    gainers = [m for m in movers if (m.get("change_pct") or 0) > 0]
    losers = [m for m in movers if (m.get("change_pct") or 0) < 0]
    top_gainer = gainers[0] if gainers else None
    top_loser = losers[0] if losers else None
    period_word = {"intraday": "the last few hours", "daily": "today's session",
                   "weekly": "the past week"}.get(summary_type, "the recent session")
    headline_parts = []
    if top_gainer:
        headline_parts.append(
            f"{top_gainer['symbol']} leads gains ({top_gainer['change_pct']:+.2f}%)")
    if top_loser:
        headline_parts.append(
            f"{top_loser['symbol']} lags ({top_loser['change_pct']:+.2f}%)")
    headline = " · ".join(headline_parts) or "Markets consolidate"
    net = sum(m.get("change_pct") or 0 for m in movers)
    if net > 3:
        sentiment = "bullish"
    elif net < -3:
        sentiment = "bearish"
    else:
        sentiment = "neutral"
    body_lines = [
        f"Across the tracked universe, price action over {period_word} "
        f"skews {sentiment}. Top gainers: " +
        ", ".join(f"{g['symbol']} ({g['change_pct']:+.2f}%)" for g in gainers[:3]) +
        ("." if gainers else "limited."),
        "Top laggards: " +
        ", ".join(f"{l['symbol']} ({l['change_pct']:+.2f}%)" for l in losers[:3]) +
        ("." if losers else "limited."),
        "Volatility remains within recent ranges; watch upcoming macro releases "
        "and central-bank commentary for the next directional cue.",
        "Not investment advice.",
    ]
    return {
        "headline": headline,
        "sentiment": sentiment,
        "body": " ".join(body_lines),
        "key_movers": [
            {"symbol": m["symbol"], "price": m.get("price"),
             "change_pct": m.get("change_pct")}
            for m in movers[:8]
        ],
    }


async def _call_llm(summary_type: str, movers: List[Dict[str, Any]]) -> Optional[Dict[str, Any]]:
    if not (HAS_LLM and EMERGENT_KEY):
        return None
    try:
        session = f"summary-{summary_type}-{int(_now().timestamp() // 900)}"
        system = (
            "You are the My Funding Bank chief market strategist. Write a concise "
            f"{summary_type} market summary based on the provided top movers. "
            "Return STRICT JSON with keys: headline (12-16 words), sentiment "
            "(bullish|neutral|bearish), body (5-7 sentences, <1200 chars). "
            "Never give investment advice; end with 'Not investment advice.'"
        )
        chat = LlmChat(api_key=EMERGENT_KEY, session_id=session,
                       system_message=system).with_model(MODEL_PROVIDER, MODEL_NAME)
        rows_txt = "\n".join(
            f"{m['symbol']}: {m.get('price')} ({m.get('change_pct'):+.2f}%)"
            for m in movers if m.get("change_pct") is not None
        )
        prompt = f"Type: {summary_type}\nTop movers:\n{rows_txt}\n\nReturn ONLY JSON."
        resp = await chat.send_message(UserMessage(text=prompt))
        text = (getattr(resp, "content", None) or str(resp)).strip()
        if text.startswith("```"):
            text = text.strip("`")
            if text.startswith("json"):
                text = text[4:]
        import json as _json
        data = _json.loads(text)
        return {
            "headline": str(data.get("headline", ""))[:240],
            "sentiment": str(data.get("sentiment", "neutral")).lower(),
            "body": str(data.get("body", ""))[:2000],
            "key_movers": [
                {"symbol": m["symbol"], "price": m.get("price"),
                 "change_pct": m.get("change_pct")}
                for m in movers[:8]
            ],
        }
    except Exception as e:
        logger.info("AI summary fell back to template (%s): %s", summary_type, e)
        return None


async def generate_summary(db, summary_type: str) -> Dict[str, Any]:
    if summary_type not in VALID_TYPES:
        raise ValueError(f"invalid type; valid={sorted(VALID_TYPES)}")
    movers = await _read_movers(db)
    ai = await _call_llm(summary_type, movers)
    if not ai:
        ai = _fallback_narrative(summary_type, movers)
    now = _now()
    start, end = _period_bounds(summary_type, now)
    doc = {
        "summary_id": f"sm_{uuid.uuid4().hex[:12]}",
        "type": summary_type,
        "period_start": start, "period_end": end,
        "headline": ai["headline"],
        "sentiment": ai["sentiment"],
        "body": ai["body"],
        "key_movers": ai["key_movers"],
        "is_ai_generated": bool(HAS_LLM and EMERGENT_KEY),
        "generated_at": now,
    }
    await db[COLL].insert_one(doc)
    doc.pop("_id", None)
    # Convert datetimes for return payload
    for k in ("period_start", "period_end", "generated_at"):
        if isinstance(doc.get(k), datetime):
            doc[k] = doc[k].isoformat()
    return doc


async def latest_summary(db, summary_type: str) -> Optional[Dict[str, Any]]:
    d = await db[COLL].find_one({"type": summary_type}, {"_id": 0},
                                 sort=[("generated_at", -1)])
    if not d:
        return None
    for k in ("period_start", "period_end", "generated_at"):
        if isinstance(d.get(k), datetime):
            d[k] = d[k].isoformat()
    return d


async def summary_history(db, summary_type: Optional[str] = None,
                          limit: int = 20) -> List[Dict[str, Any]]:
    q = {"type": summary_type} if summary_type else {}
    cur = db[COLL].find(q, {"_id": 0}).sort("generated_at", -1).limit(int(limit))
    rows = [d async for d in cur]
    for d in rows:
        for k in ("period_start", "period_end", "generated_at"):
            if isinstance(d.get(k), datetime):
                d[k] = d[k].isoformat()
    return rows


async def ensure_seed(db):
    for t in ("intraday", "daily", "weekly"):
        exists = await db[COLL].estimated_document_count()
        if exists > 0:
            # Just make sure each type has at least one entry
            has_type = await db[COLL].count_documents({"type": t})
            if has_type == 0:
                try:
                    await generate_summary(db, t)
                except Exception:
                    pass
        else:
            try:
                await generate_summary(db, t)
            except Exception:
                pass


async def delete_summary(db, summary_id: str) -> bool:
    res = await db[COLL].delete_one({"summary_id": summary_id})
    return res.deleted_count > 0
