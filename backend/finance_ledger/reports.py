"""Sprint 12.3 · Phase B — Finance report renderers (PDF / Excel / CSV).

All renderers accept the same `report_data` dict produced by
`finance_ledger.kpi.build_report_data(...)` and return a bytes payload.
On-demand only — no persistence.
"""
from __future__ import annotations
import csv
import io
import logging
from datetime import datetime
from typing import Any, Dict, List, Tuple

logger = logging.getLogger("finance_ledger.reports")


BRAND = "My Funding Bank"
TAGLINE = "Finance Report — confidential · not for redistribution"


def _fmt_dt(dt: Any) -> str:
    if not dt:
        return ""
    if isinstance(dt, str):
        return dt
    try:
        return dt.strftime("%Y-%m-%d %H:%M UTC")
    except Exception:
        return str(dt)


def _fmt_inr(v: Any) -> str:
    try:
        return "₹ " + f"{float(v):,.2f}"
    except Exception:
        return str(v)


# ---------------------------------------------------------------- CSV ------
def render_csv(report_data: Dict[str, Any]) -> bytes:
    """Simple CSV of the entry rows + one summary row on top."""
    buf = io.StringIO()
    w = csv.writer(buf)
    # Header meta
    w.writerow([BRAND, "Finance Report — " + report_data.get("report_type", "").upper()])
    r = report_data.get("range", {})
    w.writerow(["Generated At", _fmt_dt(report_data.get("generated_at"))])
    w.writerow(["Date Range",
                 f"{_fmt_dt(r.get('start'))} to {_fmt_dt(r.get('end'))}"])
    filt = report_data.get("filters", {}) or {}
    w.writerow(["Filters", ", ".join(f"{k}={v}" for k, v in filt.items() if v) or "—"])
    w.writerow([])
    # Executive summary
    w.writerow(["--- EXECUTIVE SUMMARY ---"])
    es = report_data.get("executive_summary", {}) or {}
    for k in ("total_deposits", "total_withdrawals", "wallet_balance",
               "platform_liability", "net_revenue", "todays_revenue",
               "fees", "gst", "failed_payments", "pending_withdrawals"):
        v = es.get(k)
        if isinstance(v, dict):
            w.writerow([k, v.get("amount", 0), f"count={v.get('count', 0)}"])
        else:
            w.writerow([k, v])
    w.writerow([])
    w.writerow(["--- ENTRIES ---"])
    w.writerow(["Journal ID", "Date", "Type", "User", "Amount", "Currency",
                 "Reference Type", "Reference ID", "Narration", "UTR", "Status"])
    for e in report_data.get("entries", []) or []:
        md = e.get("metadata") or {}
        w.writerow([
            e.get("journal_id"),
            _fmt_dt(e.get("entry_date")),
            e.get("txn_type"),
            e.get("user_id") or "",
            e.get("amount"),
            e.get("currency"),
            e.get("reference_type") or "",
            e.get("reference_id") or "",
            (e.get("narration") or "")[:120],
            md.get("utr") or "",
            md.get("status") or "",
        ])
    w.writerow([])
    w.writerow(["--- RECONCILIATION SUMMARY ---"])
    for mod, buckets in (report_data.get("reconciliation_summary") or {}).items():
        w.writerow([mod, *[f"{s}={c}" for s, c in buckets.items()]])
    w.writerow([])
    w.writerow(["--- SETTLEMENT SUMMARY ---"])
    for prov, s in (report_data.get("settlement_summary") or {}).items():
        w.writerow([prov, s.get("count"), _fmt_inr(s.get("amount"))])
    w.writerow([])
    w.writerow([f"— Generated by {BRAND} · {_fmt_dt(datetime.utcnow())}"])
    return buf.getvalue().encode("utf-8")


# ---------------------------------------------------------------- Excel ----
def render_excel(report_data: Dict[str, Any]) -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Font, Alignment, PatternFill, Border, Side
    from openpyxl.utils import get_column_letter

    wb = Workbook()
    thin = Side(border_style="thin", color="DDDDDD")
    header_font = Font(bold=True, size=13, color="FFFFFF")
    header_fill = PatternFill("solid", fgColor="1E293B")
    kpi_font = Font(bold=True, size=11, color="1E293B")
    kpi_fill = PatternFill("solid", fgColor="EFF6FF")

    # ======= SUMMARY sheet =========
    ws = wb.active; ws.title = "Summary"
    ws.merge_cells("A1:F1")
    ws["A1"] = f"{BRAND} — Finance Report"
    ws["A1"].font = Font(bold=True, size=18, color="1E293B")
    ws["A1"].alignment = Alignment(horizontal="left", vertical="center")
    ws.row_dimensions[1].height = 30
    ws["A2"] = TAGLINE; ws["A2"].font = Font(italic=True, size=9, color="64748B")
    ws.merge_cells("A2:F2")
    ws["A4"] = "Report Type"; ws["B4"] = (report_data.get("report_type") or "").upper()
    ws["A5"] = "Generated At"; ws["B5"] = _fmt_dt(report_data.get("generated_at"))
    r = report_data.get("range", {}) or {}
    ws["A6"] = "Date Range";  ws["B6"] = f"{_fmt_dt(r.get('start'))} → {_fmt_dt(r.get('end'))}"
    filters = report_data.get("filters", {}) or {}
    ws["A7"] = "Filters"; ws["B7"] = ", ".join(f"{k}={v}" for k, v in filters.items() if v) or "—"
    for col in ("A4", "A5", "A6", "A7"):
        ws[col].font = Font(bold=True, color="475569")

    # KPI cards (3 columns)
    ws["A9"] = "EXECUTIVE SUMMARY"; ws["A9"].font = Font(bold=True, size=12, color="1E293B")
    es = report_data.get("executive_summary", {}) or {}
    def _val(k):
        v = es.get(k)
        return v.get("amount") if isinstance(v, dict) else v
    kpis = [
        ("Total Deposits", _val("total_deposits")),
        ("Total Withdrawals", _val("total_withdrawals")),
        ("Wallet Balance", _val("wallet_balance")),
        ("Platform Liability", _val("platform_liability")),
        ("Net Revenue", _val("net_revenue")),
        ("Fees", _val("fees")),
        ("GST", _val("gst")),
        ("Failed Payments", _val("failed_payments")),
        ("Pending Withdrawals", _val("pending_withdrawals")),
    ]
    for i, (label, val) in enumerate(kpis):
        row = 11 + (i // 3) * 3
        col = 1 + (i % 3) * 2
        ws.cell(row=row, column=col, value=label).font = kpi_font
        ws.cell(row=row, column=col).fill = kpi_fill
        cell = ws.cell(row=row + 1, column=col,
                        value=_fmt_inr(val) if isinstance(val, (int, float)) else val)
        cell.font = Font(bold=True, size=13, color="1E293B")

    # Reconciliation summary
    ws2 = wb.create_sheet("Reconciliation")
    ws2["A1"] = "Module"; ws2["B1"] = "Matched"; ws2["C1"] = "Mismatch"
    ws2["D1"] = "Pending"; ws2["E1"] = "Manual Review"
    for c in "ABCDE":
        ws2[f"{c}1"].font = header_font; ws2[f"{c}1"].fill = header_fill
    row = 2
    for mod, buckets in (report_data.get("reconciliation_summary") or {}).items():
        ws2[f"A{row}"] = mod
        ws2[f"B{row}"] = buckets.get("matched", 0)
        ws2[f"C{row}"] = buckets.get("mismatch", 0)
        ws2[f"D{row}"] = buckets.get("pending", 0)
        ws2[f"E{row}"] = buckets.get("manual_review", 0)
        row += 1
    for col_i in range(1, 6):
        ws2.column_dimensions[get_column_letter(col_i)].width = 18
    ws2.freeze_panes = "A2"

    # Entries sheet
    ws3 = wb.create_sheet("Entries")
    headers = ["Journal ID", "Date", "Type", "User", "Amount (₹)", "Currency",
                "Reference Type", "Reference ID", "Narration", "UTR", "Status"]
    for i, h in enumerate(headers, 1):
        c = ws3.cell(row=1, column=i, value=h)
        c.font = header_font; c.fill = header_fill; c.alignment = Alignment(horizontal="left")
    r = 2
    for e in report_data.get("entries", []) or []:
        md = e.get("metadata") or {}
        ws3.cell(row=r, column=1, value=e.get("journal_id"))
        ws3.cell(row=r, column=2, value=_fmt_dt(e.get("entry_date")))
        ws3.cell(row=r, column=3, value=e.get("txn_type"))
        ws3.cell(row=r, column=4, value=e.get("user_id") or "")
        ws3.cell(row=r, column=5, value=float(e.get("amount") or 0)).number_format = "#,##0.00"
        ws3.cell(row=r, column=6, value=e.get("currency"))
        ws3.cell(row=r, column=7, value=e.get("reference_type") or "")
        ws3.cell(row=r, column=8, value=e.get("reference_id") or "")
        ws3.cell(row=r, column=9, value=(e.get("narration") or "")[:120])
        ws3.cell(row=r, column=10, value=md.get("utr") or "")
        ws3.cell(row=r, column=11, value=md.get("status") or "")
        r += 1
    widths = [22, 20, 22, 22, 15, 8, 20, 24, 40, 20, 12]
    for i, w in enumerate(widths, 1):
        ws3.column_dimensions[get_column_letter(i)].width = w
    ws3.freeze_panes = "A2"

    # Totals row
    if r > 2:
        ws3.cell(row=r, column=4, value="TOTAL").font = Font(bold=True)
        ws3.cell(row=r, column=5, value=float(report_data.get("total_amount", 0)))\
            .number_format = "#,##0.00"
        ws3.cell(row=r, column=5).font = Font(bold=True)

    buf = io.BytesIO(); wb.save(buf); return buf.getvalue()


# ---------------------------------------------------------------- PDF -----
def render_pdf(report_data: Dict[str, Any]) -> bytes:
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.lib import colors
    from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Table,
                                       TableStyle, PageBreak)

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15*mm, rightMargin=15*mm,
                              topMargin=15*mm, bottomMargin=15*mm,
                              title=f"{BRAND} Finance Report")
    styles = getSampleStyleSheet()
    story: List[Any] = []

    title_style = ParagraphStyle("t", parent=styles["Heading1"], fontSize=22,
                                    textColor=colors.HexColor("#1E293B"), spaceAfter=4)
    story.append(Paragraph(BRAND, title_style))
    story.append(Paragraph(f"<font size=11 color='#475569'>Finance Report — <b>{(report_data.get('report_type') or '').upper()}</b></font>",
                             styles["Normal"]))
    story.append(Paragraph(f"<font size=8 color='#64748B'><i>{TAGLINE}</i></font>",
                             styles["Normal"]))
    story.append(Spacer(1, 8))

    r = report_data.get("range", {}) or {}
    meta = [
        ["Generated at", _fmt_dt(report_data.get("generated_at"))],
        ["Date range", f"{_fmt_dt(r.get('start'))}  →  {_fmt_dt(r.get('end'))}"],
        ["Filters", ", ".join(f"{k}={v}" for k, v in (report_data.get('filters') or {}).items() if v) or "—"],
    ]
    t = Table(meta, colWidths=[35*mm, 130*mm])
    t.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#475569")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F1F5F9")),
        ("BOX", (0, 0), (-1, -1), 0.4, colors.HexColor("#E2E8F0")),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#E2E8F0")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(t); story.append(Spacer(1, 12))

    # Executive summary
    es = report_data.get("executive_summary", {}) or {}
    def _v(k):
        v = es.get(k)
        return v.get("amount") if isinstance(v, dict) else v

    kpi_rows = [
        ["Total Deposits", _fmt_inr(_v("total_deposits")),
         "Total Withdrawals", _fmt_inr(_v("total_withdrawals"))],
        ["Wallet Balance", _fmt_inr(_v("wallet_balance")),
         "Platform Liability", _fmt_inr(_v("platform_liability"))],
        ["Net Revenue", _fmt_inr(_v("net_revenue")),
         "Fees Earned", _fmt_inr(_v("fees"))],
        ["GST", _fmt_inr(_v("gst")),
         "Failed Payments", str(_v("failed_payments") or 0)],
        ["Pending Withdrawals", str(_v("pending_withdrawals") or 0),
         "Pending Settlements", str(_v("pending_settlements") or 0)],
    ]
    story.append(Paragraph("<b>Executive Summary</b>", styles["Heading3"]))
    kpi_tbl = Table(kpi_rows, colWidths=[42*mm, 42*mm, 42*mm, 42*mm])
    kpi_tbl.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#EFF6FF")),
        ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#EFF6FF")),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#1E40AF")),
        ("TEXTCOLOR", (2, 0), (2, -1), colors.HexColor("#1E40AF")),
        ("FONTNAME", (1, 0), (1, -1), "Helvetica-Bold"),
        ("FONTNAME", (3, 0), (3, -1), "Helvetica-Bold"),
        ("BOX", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#E2E8F0")),
        ("LEFTPADDING", (0, 0), (-1, -1), 6), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(kpi_tbl); story.append(Spacer(1, 12))

    # Reconciliation summary
    story.append(Paragraph("<b>Reconciliation Summary</b>", styles["Heading3"]))
    recon = report_data.get("reconciliation_summary") or {}
    recon_rows: List[List[str]] = [["Module", "Matched", "Mismatch", "Pending", "Manual Review"]]
    for mod, buckets in recon.items():
        recon_rows.append([mod,
                           str(buckets.get("matched", 0)),
                           str(buckets.get("mismatch", 0)),
                           str(buckets.get("pending", 0)),
                           str(buckets.get("manual_review", 0))])
    if len(recon_rows) == 1:
        recon_rows.append(["—", "0", "0", "0", "0"])
    rt = Table(recon_rows, colWidths=[45*mm, 30*mm, 30*mm, 30*mm, 35*mm])
    rt.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E293B")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("BOX", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#E2E8F0")),
        ("ALIGN", (1, 1), (-1, -1), "RIGHT"),
    ]))
    story.append(rt); story.append(Spacer(1, 12))

    # Settlement summary
    settle = report_data.get("settlement_summary") or {}
    story.append(Paragraph("<b>Settlement Summary</b>", styles["Heading3"]))
    sr = [["Provider", "Count", "Amount"]]
    for prov, v in settle.items():
        sr.append([prov.title(), str(v.get("count") or 0), _fmt_inr(v.get("amount") or 0)])
    if len(sr) == 1:
        sr.append(["—", "0", _fmt_inr(0)])
    st = Table(sr, colWidths=[60*mm, 40*mm, 60*mm])
    st.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0F766E")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("BOX", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#E2E8F0")),
        ("ALIGN", (1, 1), (-1, -1), "RIGHT"),
    ]))
    story.append(st); story.append(Spacer(1, 14))

    # Entry table (up to 200 rows in PDF — full list in Excel/CSV)
    entries = report_data.get("entries", []) or []
    story.append(Paragraph(
        f"<b>Transactions</b> <font size=8 color='#64748B'>({len(entries)} entries — first {min(200, len(entries))} shown)</font>",
        styles["Heading3"]))
    header = ["Date", "Type", "User", "Amount", "Ref"]
    body: List[List[str]] = [header]
    for e in entries[:200]:
        body.append([
            _fmt_dt(e.get("entry_date"))[:16],
            (e.get("txn_type") or "")[:20],
            (e.get("user_id") or "")[:14],
            _fmt_inr(e.get("amount")),
            (e.get("reference_id") or "")[:22],
        ])
    if len(body) == 1:
        body.append(["—", "—", "—", "—", "—"])
    et = Table(body, colWidths=[36*mm, 40*mm, 30*mm, 30*mm, 45*mm], repeatRows=1)
    et.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#334155")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("BOX", (0, 0), (-1, -1), 0.3, colors.HexColor("#CBD5E1")),
        ("INNERGRID", (0, 0), (-1, -1), 0.2, colors.HexColor("#E2E8F0")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1),
         [colors.HexColor("#FFFFFF"), colors.HexColor("#F8FAFC")]),
        ("ALIGN", (3, 1), (3, -1), "RIGHT"),
    ]))
    story.append(et)

    def _footer(canvas, _doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.HexColor("#64748B"))
        canvas.drawString(15 * mm, 8 * mm,
                          f"{BRAND} · Generated {_fmt_dt(report_data.get('generated_at'))}")
        canvas.drawRightString(A4[0] - 15 * mm, 8 * mm,
                                f"Page {_doc.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()
